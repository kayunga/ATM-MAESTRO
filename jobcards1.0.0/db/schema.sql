-- Job Cards: standalone database. Idempotent - safe to re-run (npm run db:migrate).
CREATE TABLE IF NOT EXISTS users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  email text NOT NULL,
  password_hash text NOT NULL,
  role text NOT NULL DEFAULT 'engineer' CHECK (role IN ('admin','engineer')),
  active boolean NOT NULL DEFAULT true,          -- deactivate, never delete: job history points at users
  must_change_password boolean NOT NULL DEFAULT true,
  signature text,                                -- engineer's saved signature (PNG data URL)
  failed_logins int NOT NULL DEFAULT 0,
  locked_until timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS users_email_uq ON users (lower(email));

CREATE TABLE IF NOT EXISTS banks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  short_code text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS banks_name_uq ON banks (lower(name));

CREATE TABLE IF NOT EXISTS atms (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  terminal_id text NOT NULL,
  serial_number text,
  model text,
  location text NOT NULL,
  address text,
  bank_id bigint REFERENCES banks(id) ON DELETE SET NULL,
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active','offline','under_maintenance','decommissioned')),
  has_gbna boolean NOT NULL DEFAULT false,      -- GBNA (deposit module) fitted: adds the GBNA checks to this ATM's PM cards
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE atms ADD COLUMN IF NOT EXISTS has_gbna boolean NOT NULL DEFAULT false;
CREATE UNIQUE INDEX IF NOT EXISTS atms_terminal_uq ON atms (lower(terminal_id));
CREATE INDEX IF NOT EXISTS atms_bank_idx ON atms (bank_id);

CREATE TABLE IF NOT EXISTS job_cards (
  job_no bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 11417) PRIMARY KEY,
  job_type text NOT NULL CHECK (job_type IN ('repair','maintenance','incident')),
  atm_id bigint REFERENCES atms(id) ON DELETE SET NULL,
  created_by bigint REFERENCES users(id) ON DELETE SET NULL,
  -- snapshot of what was on the card when signed: a service record must not change if an ATM is later edited
  bank text, site text, atm_name text, model text, serial_number text,
  service_date date, start_time time, end_time time,
  fault_category text, description text, parts_used text, status text,
  checklist jsonb, notes text,
  technician text, technician_phone text, technician_signature text,
  custodian1_name text, custodian1_signature text,
  custodian2_name text, custodian2_signature text,
  source text, raw_message text, assigned_at timestamptz,
  voided_at timestamptz, voided_by bigint REFERENCES users(id) ON DELETE SET NULL, void_reason text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS job_cards_atm_idx  ON job_cards (atm_id);
CREATE INDEX IF NOT EXISTS job_cards_date_idx ON job_cards (service_date DESC);

CREATE TABLE IF NOT EXISTS audit_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint REFERENCES users(id) ON DELETE SET NULL,
  action text NOT NULL,
  entity text NOT NULL,
  entity_id text,
  detail jsonb,
  at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS audit_at_idx ON audit_log (at DESC);

